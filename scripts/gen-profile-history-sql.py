#!/usr/bin/env python3
"""Regenerates database/queries/profile_history.sql from
../kaderisasi-web-be/app/services/profile_history_service.ts (historyPage):
the same statements with $n parameters instead of knex bindings."""
import re, pathlib
root = pathlib.Path(__file__).resolve().parent.parent
src = (root.parent / 'kaderisasi-web-be/app/services/profile_history_service.ts').read_text()

def parts(fn):
    i = src.index('export async function ' + fn)
    j = src.find('export async function', i + 10)
    return re.findall(r'`([^`]*)`', src[i:len(src) if j < 0 else j], re.S)

act, con, ach = parts('activityHistory'), parts('consultationHistory'), parts('achievementHistory')
broader = re.search(r'"( OR strpos\(lower\(coalesce\(r\.description[^"]*)"', src).group(1)

def page(owned, item, summary, joins=''):
    return f"""WITH input AS (SELECT $1::integer AS user_id, $2::text AS search, $3::text AS status), owned AS ({owned}),
      filtered AS (SELECT owned.* FROM owned, input WHERE search_match AND (input.status='' OR owned.status::text=input.status)),
      page AS (SELECT * FROM filtered ORDER BY sort_date DESC NULLS LAST,id DESC LIMIT $4::bigint OFFSET $5::bigint)
     SELECT COALESCE((SELECT jsonb_agg({item} ORDER BY p.sort_date DESC NULLS LAST,p.id DESC) FROM page p {joins}), '[]'::jsonb)::jsonb AS items,
       (SELECT count(*) FROM filtered) AS total,
       (SELECT {summary} FROM owned)::jsonb AS summary"""

queries = {
    'ActivityHistory': page(act[0].replace('${broaderSearch}', broader), act[1], act[2], act[3]),
    'ActivityHistoryByName': page(act[0].replace('${broaderSearch}', ''), act[1], act[2], act[3]),
    'ConsultationHistory': page(con[0], con[1], con[2], 'LEFT JOIN admin_users counselor ON counselor.id=p.counselor_id'),
    'AchievementHistory': page(ach[0], ach[1], ach[2]),
}
out = ['-- Generated by scripts/gen-profile-history-sql.py from', '-- kaderisasi-web-be/app/services/profile_history_service.ts. Do not edit.', '']
for name, sql in queries.items():
    out += [f'-- name: {name} :one', sql.strip() + ';', '']
(root / 'database/queries/profile_history.sql').write_text('\n'.join(out))
